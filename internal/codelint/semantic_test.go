// detailFindings lints source saved as file and counts the findings of rule
// whose description mentions detail.
func detailFindings(t *testing.T, file, source, rule, detail string) int {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, file), []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	out, _, err := lintIn(t, dir, "-nf")
	if err != nil && !errors.Is(err, command.ErrViolations) {
		t.Fatal(err)
	}
	n := 0
	for line := range strings.Lines(out) {
		if strings.Contains(line, " - "+rule+":") && strings.Contains(line, detail) {
			n++
		}
	}
	return n
}

// ruleFindings lints source saved as file and counts the findings of rule.
func ruleFindings(t *testing.T, file, source, rule string) int {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, file)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	out, stderr, err := lintIn(t, dir, "-nf")
	if err != nil && !errors.Is(err, command.ErrViolations) {
		t.Fatal(err)
	}
	if stderr != "" {
		t.Fatalf("stderr = %q", stderr)
	}
	return strings.Count(out, " - "+rule+":")
}
